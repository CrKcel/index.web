// Authored track samples on the opening clock's own 25 fps frame grid at
// 1920×1080. Monotone cubic interpolation preserves the measured speeds between
// samples; unlike easing each interval separately, it does not stop at every key.
type Key = readonly [number, number];
export function track(keys: readonly Key[], frame: number): number {
  if (frame <= keys[0][0]) return keys[0][1];
  const last = keys.length - 1;
  if (frame >= keys[last][0]) return keys[last][1];
  const slope = (i: number) =>
    (keys[i + 1][1] - keys[i][1]) / (keys[i + 1][0] - keys[i][0]);
  const tangent = (i: number) => {
    if (i === 0) return slope(0);
    if (i === last) return slope(last - 1);
    const a = slope(i - 1),
      b = slope(i);
    if (a * b <= 0) return 0;
    const h0 = keys[i][0] - keys[i - 1][0],
      h1 = keys[i + 1][0] - keys[i][0];
    const w0 = 2 * h1 + h0,
      w1 = h1 + 2 * h0;
    return (w0 + w1) / (w0 / a + w1 / b);
  };
  let i = 0;
  while (frame > keys[i + 1][0]) i++;
  const h = keys[i + 1][0] - keys[i][0],
    p = (frame - keys[i][0]) / h;
  return (
    (2 * p ** 3 - 3 * p ** 2 + 1) * keys[i][1] +
    (p ** 3 - 2 * p ** 2 + p) * h * tangent(i) +
    (-2 * p ** 3 + 3 * p ** 2) * keys[i + 1][1] +
    (p ** 3 - p ** 2) * h * tangent(i + 1)
  );
}

// All three lines repeat this trajectory with a two-frame offset. Ink starts
// arriving before the fastest movement, then the translation has a long tail.
const brandX = [
  234, 216, 181, 143, 115, 94, 78, 65, 54, 45, 38, 31, 26, 21, 17, 13, 10, 8, 6,
  4, 3, 2, 1, 0,
];
const brandKeys = brandX.map((x, i) => [i, x] as const);
export const brandTrack = (frame: number, line: number) => {
  const local = frame - 50 - line * 2;
  return {
    x: track(brandKeys, local),
    opacity: track(
      [
        [-1, 0],
        [0, 0.4],
        [1, 0.65],
        [2, 0.88],
        [3, 1],
      ],
      local,
    ),
  };
};

